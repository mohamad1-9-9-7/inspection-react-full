export function t(lang, key, ...args) {
  let s = I18N[lang]?.[key] ?? I18N.en[key] ?? key;
  args.forEach((a, i) => { s = s.replace(new RegExp(`\\{${i}\\}`, "g"), String(a)); });
  return s;
}
